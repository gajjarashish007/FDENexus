def assistant_reply(message: str) -> str:
    m = (message or "").lower()
    for key, answer in HELP_TOPICS.items():
        if key in m:
            return answer
    if any(w in m for w in ["hi", "hello", "hey"]):
        return ("Hi! I can help you use the Self-Service Portal. Ask me about creating a namespace or database, "
                "how approvals work, risk tiers, cost, or how to track a request.")
    if "create" in m or "provision" in m or "deploy" in m:
        return ("To create infrastructure, open the Service Catalog, choose an item, fill the form and submit. "
                "You'll see an estimated cost and, if needed, it will route to the Approval Center. "
                "Everything here is a governed, audited request. Say the service name (for example 'namespace' or 'database') for specifics.")
    if "help" in m or "?" in m:
        return ("I can explain the catalog, requests, approvals, risk tiers, cost and deployment tracking. "
                "What would you like to do?")
    return ("I'm a demo assistant for the Self-Service Portal. Try asking about 'create a namespace', "
            "'how do approvals work', 'risk tiers', or 'track my request'.")


# ----------------------------------------------------------------- AWS account connectivity
def profiles_for_account(acct_id: str) -> list[str]:
    """Profile names in the host's ~/.aws/config that point at this account (SSO account id or role ARN).
    Reads only the config file; no credentials are loaded."""
    try:
        import botocore.session
        profiles = botocore.session.Session().full_config.get("profiles", {})
    except Exception:
        return []
    out = []
    for name, p in profiles.items():
        if str(p.get("sso_account_id", "")) == acct_id or f":{acct_id}:" in str(p.get("role_arn", "")):
            out.append(name)
    return sorted(out)


def test_aws_account(acct: dict) -> tuple[str, str]:
    """Verify an AWS account connection with read-only STS calls. Returns (status, note).

    The test never changes anything, so it is real even in simulation mode (M01_DEMO=1).
    Only M01_LIVE_READS=0 (fully offline demo) skips it.
    """
    if not config.LIVE_READS:
        return "connected", "Offline demo (M01_LIVE_READS=0): details look valid, no AWS call was made."
    try:
        import boto3
        from botocore.exceptions import BotoCoreError, ClientError, ProfileNotFound
    except ImportError:
        return "failed", "boto3 is not installed on the portal host."
    try:
        if acct["method"] == "profile":
            ident = boto3.Session(profile_name=acct.get("profile") or None, region_name=acct["region"]).client("sts").get_caller_identity()
            how = f"profile {acct.get('profile')}"
        elif acct["method"] == "instance-role":
            ident = boto3.client("sts", region_name=acct["region"]).get_caller_identity()
            how = "host credentials"
        else:
            kwargs = {"RoleArn": acct["role_arn"], "RoleSessionName": "fde-nexus-check", "DurationSeconds": 900}
            if acct.get("external_id"):
                kwargs["ExternalId"] = acct["external_id"]
            creds = boto3.client("sts", region_name=acct["region"]).assume_role(**kwargs)["Credentials"]
            ident = boto3.client("sts", region_name=acct["region"], aws_access_key_id=creds["AccessKeyId"],
                                 aws_secret_access_key=creds["SecretAccessKey"],
                                 aws_session_token=creds["SessionToken"]).get_caller_identity()
            how = "AssumeRole"
        if ident["Account"] != acct["id"]:
            return "failed", f"Credentials belong to account {ident['Account']}, not {acct['id']} ({how})."
        return "connected", f"Verified with {how}: {ident['Arn']}"
    except ProfileNotFound:
        return "failed", f"Profile '{acct.get('profile')}' is not in the portal host's ~/.aws/config."
    except ClientError as e:
        code = e.response.get("Error", {}).get("Code", "")
        hint = {"AccessDenied": "The role's trust policy does not allow the portal's identity, or the external ID is wrong.",
                "InvalidClientTokenId": "The portal host has no valid AWS credentials.",
                "ExpiredToken": "The credentials have expired. For SSO run: aws sso login --profile <name>.",
                "NoSuchEntity": "The role does not exist in the target account."}.get(code, "")
        return "failed", f"{code or 'Error'}: {str(e)[:200]} {hint}".strip()
    except BotoCoreError as e:
        msg = str(e)
        if "Token has expired" in msg or "SSO" in msg or "sso" in msg:
            msg += f" Run: aws sso login --profile {acct.get('profile') or '<profile>'}"
        elif "Unable to locate credentials" in msg:
            found = profiles_for_account(acct["id"]) if acct["method"] != "profile" else []
            if found:
                msg = (f"No base AWS credentials on the portal host for {acct['method']}. "
                       f"This host has profile(s) for account {acct['id']}: {', '.join(found)}. "
                       f"Switch this account to the profile method (Use profile button), or start the portal with AWS_PROFILE={found[0]}.")
            else:
                msg += " Give the portal host an IAM role, start it with AWS_PROFILE=<profile>, or use the 'profile' method."
        return "failed", msg[:300]
