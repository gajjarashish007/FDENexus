# ----------------------------------------------------------------- YAML gen
def generate_manifest(item: dict, inputs: dict) -> str:
    """Return a reviewable manifest string for a catalog item + inputs."""
    iid = item["id"]
    if iid == "k8s-namespace":
        return _ns_manifest(inputs)
    if iid == "env-baseline":
        return _env_manifest(inputs)
    if iid == "postgres-db":
        return _db_manifest(inputs)
    if iid == "vpc-network":
        return _vpc_manifest(inputs)
    return _generic_manifest(item, inputs)


def _ns_manifest(i: dict) -> str:
    name = i.get("name", "team-staging")
    cpu, mem = i.get("cpu", 8), i.get("memory", 16)
    netpol = i.get("netpol", True)
    manifest = f"""# Generated by FDE Nexus Self-Service Portal. Review before use.
apiVersion: v1
kind: Namespace
metadata:
  name: {name}
  labels:
    team: {i.get('team', name.split('-')[0])}
    managed-by: fde-nexus
---
apiVersion: v1
kind: ResourceQuota
metadata:
  name: {name}-quota
  namespace: {name}
spec:
  hard:
    requests.cpu: "{cpu}"
    requests.memory: {mem}Gi
    limits.cpu: "{cpu}"
    limits.memory: {mem}Gi
"""
    if netpol:
        manifest += f"""---
apiVersion: networking.k8s.io/v1
kind: NetworkPolicy
metadata:
  name: default-deny
  namespace: {name}
spec:
  podSelector: {{}}
  policyTypes: [Ingress, Egress]
"""
    return manifest


def _env_manifest(i: dict) -> str:
    return f"""# Generated by FDE Nexus. Atmos stack configuration. Review before use.
import:
  - catalog/standard-environment
vars:
  team: {i.get('team', 'Platform')}
  environment: {i.get('environment', 'non-production')}
  region: {i.get('region', config.AWS_REGION)}
  tags:
    team: {i.get('team', 'Platform')}
    managed-by: fde-nexus
components:
  terraform:
    vpc:
      vars: {{ cidr_block: 10.0.0.0/16, availability_zones: 3 }}
    logging:
      vars: {{ enabled: true }}
    budgets:
      vars: {{ monthly_limit_usd: {i.get('budget', 500)} }}
"""


def _db_manifest(i: dict) -> str:
    return f"""# Generated by FDE Nexus. Terraform-ready values. Review before use.
database:
  engine: postgres
  owner_team: {i.get('team', 'app')}
  environment: {i.get('environment', 'non-production')}
  instance_class: {i.get('instance_class', 'db.r6g.large')}
  multi_az: {str(bool(i.get('multi_az', True))).lower()}
  storage_encrypted: true
  kms_key: customer-managed
  backup:
    retention_days: {i.get('backup_days', 7)}
    point_in_time_recovery: true
"""


def _vpc_manifest(i: dict) -> str:
    return f"""# Generated by FDE Nexus. Terraform-ready values. Review before use.
vpc:
  owner_team: {i.get('team', 'Platform')}
  cidr_block: {i.get('cidr', '10.0.0.0/16')}
  availability_zones: {i.get('azs', 3)}
  nat_gateways: {i.get('azs', 3)}
  flow_logs: true
  tags: {{ managed-by: fde-nexus }}
"""


def _generic_manifest(item: dict, i: dict) -> str:
    lines = [f"# Generated by FDE Nexus for {item['name']}. Review before use.",
             f"resource:", f"  type: {item['id']}"]
    for k, v in i.items():
        lines.append(f"  {k}: {v}")
    return "\n".join(lines) + "\n"


# ----------------------------------------------------------------- plan / apply
def plan_lines(item: dict, inputs: dict, destructive: bool = False) -> list[str]:
    name = item["name"]
    lines = [
        "$ terraform plan",
        "Initializing modules...",
        "Initializing provider plugins...",
        f"Refreshing state for {name}...",
        "",
        "Terraform will perform the following actions:",
    ]
    if destructive:
        lines += [
            f"  # {item['id']}.main will be DESTROYED",
            "  - resource would be removed",
            "",
            "Plan: 0 to add, 0 to change, 1 to destroy.",
            "WARNING: this plan destroys resources.",
        ]
    else:
        lines += [
            f"  # {item['id']}.main will be created",
            "  + resource will be created",
            f"  + name = \"{inputs.get('name', name)}\"",
            "",
            "Plan: 1 to add, 0 to change, 0 to destroy.",
        ]
    lines += ["", "[policy] OPA evaluation ............. allow",
              "[scan]   IaC security scan ........... 1 advisory",
              f"[cost]   estimated cost .............. {item.get('est_cost', 'n/a')}"]
    return lines


